/**
 * The module's own words, from its key to the catalogue's.
 *
 * ## Why a map and not `str(S.desktop_ss_…)` at each call site
 *
 * The web names this module's text `script_supervision_<thing>` in its own
 * `en.js`, and every screen reads it as `t('script_supervision_scene')`. The
 * desktop's catalogue is one catalogue for the whole app and refuses a second
 * key for text that already exists — so roughly one in four of this module's
 * words IS an app word already (`cancel`, `delete`, `camera`, `location`,
 * `approved`), translated into 22 languages under a name of its own.
 *
 * This map is where those two facts meet: a screen keeps the web's own word
 * ([t]`("scene")`), and the map says which catalogue key carries it. Written
 * once rather than resolved per call, so a key that goes missing is a compile
 * error here instead of blank text on a screen.
 *
 * A key with no row reads as the key itself rather than as nothing — the same
 * rule `str` follows — which is what a screen added before its words are.
