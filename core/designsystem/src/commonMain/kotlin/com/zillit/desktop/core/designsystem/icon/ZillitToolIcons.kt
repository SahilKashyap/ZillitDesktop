    /**
     * One glyph from Android's `pathData`, filled the way the phone fills it.
     *
     * Parsed rather than transcribed: the phone's drawables are the source of
     * truth, and hand-copied coordinates would rot the first time one changes.
     */
    private fun toolIcon(name: String, viewport: Float, paths: List<String>): ImageVector =
        ImageVector.Builder(
            name = name,
            defaultWidth = ICON_SIZE,
            defaultHeight = ICON_SIZE,
            viewportWidth = viewport,
            viewportHeight = viewport,
        ).apply {
            paths.forEach { data ->
                addPath(
                    pathData = PathParser().parsePathString(data).toNodes(),
                    fill = SolidColor(Color.Black),
                )
            }
        }.build()

    private val ICON_SIZE = 24.dp
