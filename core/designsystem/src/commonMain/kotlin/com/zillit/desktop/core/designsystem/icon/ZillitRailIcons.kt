    /** A fill-only icon on a square canvas — the common case above. */
    private fun railIcon(name: String, viewport: Float, paths: List<String>): ImageVector =
        ImageVector.Builder(
            name = name,
            defaultWidth = ICON_SIZE,
            defaultHeight = ICON_SIZE,
            viewportWidth = viewport,
            viewportHeight = viewport,
        ).apply { paths.forEach { data -> fillPath(data) } }.build()

    private fun ImageVector.Builder.fillPath(data: String) {
        addPath(
            pathData = PathParser().parsePathString(data).toNodes(),
            fill = SolidColor(Color.Black),
        )
    }

    /** The cnc SVG's stroke style, verbatim: 30-wide, round everything. */
    private fun ImageVector.Builder.strokedPath(data: String) {
        addPath(
            pathData = PathParser().parsePathString(data).toNodes(),
            stroke = SolidColor(Color.Black),
            strokeLineWidth = CNC_STROKE,
            strokeLineCap = StrokeCap.Round,
            strokeLineJoin = StrokeJoin.Round,
        )
    }

